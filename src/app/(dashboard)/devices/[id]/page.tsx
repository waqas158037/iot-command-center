import Link from "next/link";
import { Activity, ShieldAlert } from "lucide-react";
import { requirePageUser } from "@/lib/auth/session";
import { env } from "@/lib/env";
import { formatDateTime, formatRelative, resolveRange, sp, titleCase } from "@/lib/format";
import { formatMeasurementValue, getMeasurement, listMeasurements } from "@/lib/telemetry/measurements";
import { deviceStatusHistory, getDevice } from "@/server/services/devices";
import { deviceLatest, querySeries, chooseBucket, rawReadings } from "@/server/services/telemetry-query";
import { listAlerts } from "@/server/services/alerts";
import { PageHeader } from "@/components/layout/page-header";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { DeviceStatusBadge, SimulatedBadge, SourceBadge } from "@/components/dashboard/status-badges";
import { Badge } from "@/components/ui/badge";
import { AlertBanner } from "@/components/ui/alert-banner";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { TelemetryChart } from "@/components/telemetry/telemetry-chart";
import { RANGE_OPTIONS } from "@/lib/format";
import { UrlFilters } from "@/components/dashboard/dashboard-filters";
import { LiveIndicator, LiveProvider } from "@/components/telemetry/realtime";
import { CredentialPanel } from "@/components/devices/credential-panel";
import { SensorManager } from "@/components/devices/sensor-manager";
import { DeviceActions } from "@/components/devices/device-actions";
import { AlertTable } from "@/components/alerts/alert-table";
import { orNotFound } from "../../shared";

export const metadata = { title: "Device" };

export default async function DevicePage({ params, searchParams }: PageProps<"/devices/[id]">) {
  const user = await requirePageUser();
  const { id } = await params;
  const query = await searchParams;
  const device = await orNotFound(getDevice(user, id));
  const { from, to } = resolveRange(query, "24h");
  const tz = user.timezone;
  const e = env();

  const [sensors, history, readings, alerts] = await Promise.all([
    deviceLatest(user, id),
    deviceStatusHistory(user, id, 30),
    rawReadings(user, { deviceId: id, from, to, pageSize: 25 }),
    listAlerts(user, { projectId: device.projectId, deviceId: id, pageSize: 10 }),
  ]);
  const chartSensorId = sp(query, "sensorId") ?? sensors.find((s) => s.isActive && getMeasurement(s.sensorType)?.kind === "NUMERIC")?.id;
  const chartSensor = sensors.find((s) => s.id === chartSensorId);
  const series = chartSensor ? (await querySeries([chartSensor.id], from, to, chooseBucket(from, to, "auto"))).series : [];
  const disabled = device.status === "DISABLED";
  const isSim = device.protocol === "SIMULATED";

  return (
    <LiveProvider projectId={device.projectId} deviceId={id}>
      <PageHeader
        title={device.name}
        description={<><span className="font-mono">{device.deviceIdentifier}</span> · <Link className="hover:underline" href={`/projects/${device.project.id}`}>{device.project.name}</Link></>}
        badges={<><DeviceStatusBadge status={device.status} />{isSim ? <SimulatedBadge /> : <Badge variant="outline">{device.protocol}</Badge>}</>}
        actions={<><LiveIndicator /><DeviceActions deviceId={id} disabled={disabled} canUpdate={device.access.canUpdate} canConfigure={device.access.canConfigure} canDeactivate={device.access.canDeactivate}
          device={{ name: device.name, hardwareModel: device.hardwareModel, firmwareVersion: device.firmwareVersion, locationDescription: device.locationDescription, latitude: device.latitude?.toString() ?? "", longitude: device.longitude?.toString() ?? "", heartbeatTimeoutSec: device.heartbeatTimeoutSec?.toString() ?? "" }} /></>}
      />
      {isSim && <AlertBanner className="mb-4">This is a simulated device. Its readings are generated by the platform simulator and are not hardware measurements.</AlertBanner>}
      {device.project.projectType.isSensitive && <AlertBanner variant="warning" className="mb-4"><ShieldAlert className="size-4 shrink-0" /><span>Academic demonstration only. Readings are not medical measurements and must not be used for diagnosis or treatment.</span></AlertBanner>}

      <div className="grid gap-5 xl:grid-cols-3">
        <Card>
          <CardHeader className="pb-2"><CardTitle className="text-base">Overview</CardTitle></CardHeader>
          <CardContent>
            <dl className="grid grid-cols-2 gap-3 text-sm">
              <div><dt className="text-xs text-muted-foreground">Last seen</dt><dd title={device.lastSeenAt ? formatDateTime(device.lastSeenAt, tz) : undefined}>{device.lastSeenAt ? formatRelative(device.lastSeenAt) : "Never"}</dd></div>
              <div><dt className="text-xs text-muted-foreground">Heartbeat timeout</dt><dd>{device.heartbeatTimeoutEffective}s{device.heartbeatTimeoutSec ? "" : " (default)"}</dd></div>
              <div><dt className="text-xs text-muted-foreground">Hardware</dt><dd>{device.hardwareModel || "—"}</dd></div>
              <div><dt className="text-xs text-muted-foreground">Firmware</dt><dd>{device.firmwareVersion || "—"}</dd></div>
              <div className="col-span-2"><dt className="text-xs text-muted-foreground">Location</dt><dd>{device.locationDescription || "—"}{device.latitude !== null && device.longitude !== null && <span className="text-muted-foreground"> ({Number(device.latitude).toFixed(4)}, {Number(device.longitude).toFixed(4)})</span>}</dd></div>
              <div><dt className="text-xs text-muted-foreground">Registered</dt><dd>{formatDateTime(device.createdAt, tz)}</dd></div>
              <div><dt className="text-xs text-muted-foreground">Sensors</dt><dd>{device._count.sensors}</dd></div>
            </dl>
          </CardContent>
        </Card>
        <Card className="xl:col-span-2">
          <CardHeader className="gap-3 pb-2">
            <CardTitle className="text-base">History{chartSensor ? `: ${chartSensor.name}` : ""}</CardTitle>
            <UrlFilters filters={[
              { name: "range", label: "Date range", options: RANGE_OPTIONS, fallback: "24h" },
              { name: "sensorId", label: "Sensor", options: sensors.filter((s) => getMeasurement(s.sensorType)?.kind !== "EVENT").map((s) => ({ value: s.id, label: s.name })), fallback: chartSensorId },
            ]} />
          </CardHeader>
          <CardContent>
            <TelemetryChart timeZone={tz} series={series.map((s) => ({ sensorId: s.sensorId, name: s.name, deviceName: s.deviceName, sensorType: s.sensorType, unit: s.unit, isSimulated: s.isSimulated, points: s.points }))} />
          </CardContent>
        </Card>
      </div>

      <Card className="mt-5">
        <CardHeader className="pb-2"><CardTitle className="text-base">Sensors and latest readings</CardTitle></CardHeader>
        <CardContent>
          <SensorManager
            deviceId={id}
            canManage={device.access.canManageSensors && !disabled}
            measurements={listMeasurements().map((m) => ({ key: m.key, label: m.label, unit: m.canonicalUnit }))}
            sensors={sensors.map((s) => {
              const full = s as typeof s & { minValue?: unknown; maxValue?: unknown };
              return {
                id: s.id, sensorKey: s.sensorKey, name: s.name, sensorType: s.sensorType, unit: s.unit, origin: s.origin, isActive: s.isActive,
                measurementLabel: getMeasurement(s.sensorType)?.label ?? s.sensorType,
                minValue: full.minValue != null ? Number(full.minValue) : null,
                maxValue: full.maxValue != null ? Number(full.maxValue) : null,
                latest: s.latest ? { display: formatMeasurementValue(s.sensorType, s.latest.value), ago: formatRelative(s.latest.occurredAt), source: s.latest.source } : null,
              };
            })}
          />
        </CardContent>
      </Card>

      <div className="mt-5 grid gap-5 xl:grid-cols-2">
        <Card>
          <CardHeader className="pb-2"><CardTitle className="text-base">Credentials</CardTitle><CardDescription>Secrets are stored hashed. Only the prefix is shown.</CardDescription></CardHeader>
          <CardContent>
            <CredentialPanel deviceId={id} deviceIdentifier={device.deviceIdentifier} protocol={device.protocol} canManage={device.access.canManageCredentials} disabled={disabled} timeZone={tz} appUrl={e.APP_URL} topicPrefix={e.MQTT_TOPIC_PREFIX}
              credentials={device.credentials.map((c) => ({ id: c.id, secretPrefix: c.secretPrefix, credentialVersion: c.credentialVersion, expiresAt: c.expiresAt?.toISOString() ?? null, revokedAt: c.revokedAt?.toISOString() ?? null, lastUsed: c.lastUsedAt ? formatRelative(c.lastUsedAt) : "never", state: credentialState(c), createdAt: c.createdAt.toISOString() }))} />
          </CardContent>
        </Card>
        <Card>
          <CardHeader className="pb-2"><CardTitle className="flex items-center gap-2 text-base"><Activity className="size-4" /> Connectivity history</CardTitle></CardHeader>
          <CardContent>
            {history.length === 0 ? <p className="text-sm text-muted-foreground">No status changes recorded.</p> : (
              <ol className="relative grid gap-3 border-l pl-4 text-sm">
                {history.map((h) => (
                  <li key={h.id} className="relative">
                    <span className="absolute top-1.5 -left-[21px] size-2.5 rounded-full border-2 border-background bg-muted-foreground" aria-hidden />
                    <div className="flex flex-wrap items-center gap-2">{h.previousStatus && <><DeviceStatusBadge status={h.previousStatus} /><span aria-hidden>→</span></>}<DeviceStatusBadge status={h.newStatus} /></div>
                    <p className="mt-0.5 text-xs text-muted-foreground">{h.reason} · {formatDateTime(h.occurredAt, tz)}</p>
                  </li>
                ))}
              </ol>
            )}
          </CardContent>
        </Card>
      </div>

      <Card className="mt-5">
        <CardHeader className="pb-2"><CardTitle className="text-base">Recent alerts</CardTitle></CardHeader>
        {alerts.items.length === 0 ? <CardContent><p className="text-sm text-muted-foreground">No alerts for this device.</p></CardContent> : <AlertTable alerts={alerts.items} showProject={false} />}
      </Card>

      <Card className="mt-5">
        <CardHeader className="pb-2"><CardTitle className="text-base">Latest raw readings</CardTitle><CardDescription>Newest first within the selected range. Quality flags mark late or out-of-order data.</CardDescription></CardHeader>
        <Table>
          <TableHeader><TableRow><TableHead>Time</TableHead><TableHead>Sensor</TableHead><TableHead>Value</TableHead><TableHead className="hidden sm:table-cell">Source</TableHead><TableHead className="hidden md:table-cell">Quality</TableHead></TableRow></TableHeader>
          <TableBody>
            {readings.items.map((r) => (
              <TableRow key={String(r.id)}>
                <TableCell className="whitespace-nowrap text-muted-foreground">{formatDateTime(r.occurredAt, tz, { timeStyle: "medium" })}</TableCell>
                <TableCell>{r.sensor.name}</TableCell>
                <TableCell className="tabular-nums">{formatMeasurementValue(r.sensor.sensorType, Number(r.value))}</TableCell>
                <TableCell className="hidden sm:table-cell"><SourceBadge source={r.source} /></TableCell>
                <TableCell className="hidden text-xs text-muted-foreground md:table-cell">{qualityText(r.qualityMetadata)}</TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
        {readings.items.length === 0 && <p className="p-6 text-center text-sm text-muted-foreground">No readings in this period.</p>}
      </Card>
    </LiveProvider>
  );
}

function credentialState(c: { revokedAt: Date | null; expiresAt: Date | null }) {
  if (c.revokedAt) return "Revoked" as const;
  if (c.expiresAt) return c.expiresAt.getTime() < Date.now() ? ("Expired" as const) : ("Expiring" as const);
  return "Active" as const;
}

function qualityText(meta: unknown) {
  if (!meta || typeof meta !== "object") return "OK";
  const m = meta as Record<string, unknown>;
  const flags = Object.entries(m).filter(([k, v]) => v === true && k !== "converted").map(([k]) => titleCase(k.replace(/([A-Z])/g, "_$1")));
  if (m.converted) flags.push(`Converted from ${m.originalValue} ${m.originalUnit}`);
  return flags.length ? flags.join(", ") : "OK";
}
