import type { AlertSeverity, AlertStatus, DeviceStatus, ProjectStatus, TelemetrySource } from "@prisma/client";
import { Badge, type BadgeProps } from "@/components/ui/badge";
import { FlaskConical } from "lucide-react";

type Variant = NonNullable<BadgeProps["variant"]>;

const DEVICE: Record<DeviceStatus, Variant> = { ONLINE: "success", OFFLINE: "danger", DEGRADED: "warning", UNKNOWN: "muted", DISABLED: "secondary" };
const PROJECT: Record<ProjectStatus, Variant> = { PLANNING: "info", ACTIVE: "success", PAUSED: "warning", COMPLETED: "secondary", ARCHIVED: "muted" };
const SEVERITY: Record<AlertSeverity, Variant> = { INFO: "info", LOW: "secondary", MEDIUM: "warning", HIGH: "danger", CRITICAL: "danger" };
const ALERT_STATUS: Record<AlertStatus, Variant> = { ACTIVE: "danger", ACKNOWLEDGED: "warning", RESOLVED: "success" };

const title = (s: string) => s.charAt(0) + s.slice(1).toLowerCase();

export function DeviceStatusBadge({ status }: { status: DeviceStatus }) {
  return (
    <Badge variant={DEVICE[status]}>
      <span className={`size-1.5 rounded-full ${status === "ONLINE" ? "bg-success" : status === "OFFLINE" ? "bg-destructive" : status === "DEGRADED" ? "bg-warning" : "bg-muted-foreground"}`} aria-hidden />
      {title(status)}
    </Badge>
  );
}
export function ProjectStatusBadge({ status }: { status: ProjectStatus }) {
  return <Badge variant={PROJECT[status]}>{title(status)}</Badge>;
}
export function SeverityBadge({ severity }: { severity: AlertSeverity }) {
  return <Badge variant={SEVERITY[severity]} className={severity === "CRITICAL" ? "bg-destructive text-white" : undefined}>{title(severity)}</Badge>;
}
export function AlertStatusBadge({ status }: { status: AlertStatus }) {
  return <Badge variant={ALERT_STATUS[status]}>{title(status)}</Badge>;
}
export function SimulatedBadge({ className }: { className?: string }) {
  return (
    <Badge variant="simulated" className={className} title="Generated by the simulator, not physical hardware">
      <FlaskConical aria-hidden /> Simulated
    </Badge>
  );
}
export function SourceBadge({ source }: { source: TelemetrySource }) {
  if (source === "SIMULATED") return <SimulatedBadge />;
  return <Badge variant="outline">{source === "MQTT" ? "MQTT device" : "HTTP device"}</Badge>;
}
